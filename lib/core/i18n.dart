import 'package:flutter/widgets.dart';
import 'package:shared_preferences/shared_preferences.dart';

/// App languages. English text is the key; other languages look it up.
class Lang {
  final String code;
  final String native;
  final String english;
  const Lang(this.code, this.native, this.english);
}

const languages = <Lang>[
  Lang('en', 'English', 'English'),
  Lang('hi', 'हिन्दी', 'Hindi'),
  Lang('kn', 'ಕನ್ನಡ', 'Kannada'),
  Lang('ta', 'தமிழ்', 'Tamil'),
  Lang('te', 'తెలుగు', 'Telugu'),
  Lang('ml', 'മലയാളം', 'Malayalam'),
];

class LangController extends ValueNotifier<String> {
  LangController() : super('en');
  static final instance = LangController();
  static const _key = 'language';

  Lang get current => languages.firstWhere((l) => l.code == value, orElse: () => languages.first);

  Future<void> load() async {
    final v = (await SharedPreferences.getInstance()).getString(_key);
    if (v != null && languages.any((l) => l.code == v)) value = v;
  }

  Future<void> set(String code) async {
    if (code == value) return;
    value = code;
    _rebuildAll();
    await (await SharedPreferences.getInstance()).setString(_key, code);
  }

  /// Redraws every screen so new text shows immediately (keeps the user's place).
  static void _rebuildAll() {
    void mark(Element e) {
      e.markNeedsBuild();
      e.visitChildren(mark);
    }

    WidgetsBinding.instance.rootElement?.visitChildren(mark);
  }
}

/// Translate an English string into the current language.
String t(String en) {
  final code = LangController.instance.value;
  if (code == 'en') return en;
  return _tr[code]?[en] ?? en;
}

/// Translate a template containing {x}.
String tf(String en, Object x) => t(en).replaceAll('{x}', '$x');

